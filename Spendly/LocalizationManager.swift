// ================================================
// AppLanguage
// ================================================
enum AppLanguage: Int, CaseIterable {
    case english = 0, chinese, japanese, korean, french, spanish

    var displayName: String {
        switch self {
        case .english:  return "EN English"
        case .chinese:  return "CN 中文"
        case .japanese: return "JP 日本語"
        case .korean:   return "KR 한국어"
        case .french:   return "FR Français"
        case .spanish:  return "ES Español"
        }
    }
    var flag: String {
        // Unicode scalar 方式构建旗帜 emoji，真机和模拟器都能显示
        switch self {
        case .english:  return flag(from: "US")
        case .chinese:  return flag(from: "CN")
        case .japanese: return flag(from: "JP")
        case .korean:   return flag(from: "KR")
        case .french:   return flag(from: "FR")
        case .spanish:  return flag(from: "ES")
        }
    }
    private func flag(from code: String) -> String {
        let base: UInt32 = 127397
        return code.unicodeScalars.compactMap {
            UnicodeScalar(base + $0.value)
        }.map { String($0) }.joined()
    }
    var nativeName: String {
        switch self {
        case .english:  return "English"
        case .chinese:  return "中文"
        case .japanese: return "日本語"
        case .korean:   return "한국어"
        case .french:   return "Français"
        case .spanish:  return "Español"
        }
    }
    var name: String { nativeName }
}

